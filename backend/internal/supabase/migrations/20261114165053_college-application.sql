-- Replaces global_colleges.ea_deadline / ed_deadline / rd_deadline with one row per offered cycle
-- in college_application_cycles. Existing deadlines are copied over, then the old columns are dropped.

-- one row per application cycle a college offers
create table public.college_application_cycles (
    id bigint generated by default as identity primary key,
    global_college_id bigint not null references public.global_colleges(id) on delete cascade,
    cycle text not null check (cycle in ('ED', 'ED2', 'REA', 'EA', 'RD', 'ROLLING')),
    deadline timestamptz,
    rolling_start date,
    rolling_end date,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint college_application_cycles_college_cycle_unique unique (global_college_id, cycle),

    -- every cycle except rolling needs a deadline; only rolling can have a date range
    constraint college_application_cycles_deadline_shape check (
        (cycle = 'ROLLING' and deadline is null)
        or (cycle <> 'ROLLING' and deadline is not null and rolling_start is null and rolling_end is null)
    ),
    constraint college_application_cycles_rolling_range check (
        rolling_start is null or rolling_end is null or rolling_start <= rolling_end
    )
);

-- backfill: copy the existing deadline columns into rows
insert into public.college_application_cycles (global_college_id, cycle, deadline)
select id, 'EA', ea_deadline from public.global_colleges where ea_deadline is not null
union all
select id, 'ED', ed_deadline from public.global_colleges where ed_deadline is not null
union all
select id, 'RD', rd_deadline from public.global_colleges where rd_deadline is not null
on conflict (global_college_id, cycle) do nothing;

alter table public.global_colleges
    drop column ea_deadline,
    drop column ed_deadline,
    drop column rd_deadline;

-- widen application_type to cover the new cycles
alter table public.personal_college_applications
    drop constraint personal_college_applications_application_type_check;

alter table public.personal_college_applications
    add constraint personal_college_applications_application_type_check
    check (application_type in ('ED', 'ED2', 'REA', 'EA', 'RD', 'ROLLING'));

-- interest (School Details) and the student-set application status
alter table public.personal_college_applications
    add column interest text
        check (interest in ('top_choice', 'strong_contender', 'considering')),
    add column application_status text not null default 'not_started'
        check (application_status in ('not_started', 'in_progress', 'submitted'));

-- essay progress per application looks up a student's essays for one college
create index if not exists essays_student_college_idx on public.essays (student_id, college_id);
