alter table public.extracurriculars
    add column hours_per_week numeric,
    add column weeks_per_year smallint,
    add column goals text,
    add column ready_for_application boolean not null default false,
    add column application_description text;

alter table public.extracurriculars
    add constraint extracurriculars_weeks_per_year_check
        check (weeks_per_year between 0 and 52);

alter table public.extracurriculars
    alter column description drop not null;

create table public.extracurricular_achievements (
    id bigint generated by default as identity primary key,
    extracurricular_id bigint not null
        references public.extracurriculars(id) on delete cascade,
    entry_date date not null,
    body text not null,
    created_at timestamptz not null default now(),
    modified_at timestamptz not null default now()
);

create index idx_extracurricular_achievements_extracurricular_id
    on public.extracurricular_achievements (extracurricular_id);

create trigger extracurricular_achievements_set_modified_at
before update on public.extracurricular_achievements
for each row
execute function public.set_modified_at();

create table public.extracurricular_notes (
    id bigint generated by default as identity primary key,
    extracurricular_id bigint not null
        references public.extracurriculars(id) on delete cascade,
    body text not null,
    created_at timestamptz not null default now(),
    modified_at timestamptz not null default now()
);

create index idx_extracurricular_notes_extracurricular_id
    on public.extracurricular_notes (extracurricular_id);

create trigger extracurricular_notes_set_modified_at
before update on public.extracurricular_notes
for each row
execute function public.set_modified_at();
