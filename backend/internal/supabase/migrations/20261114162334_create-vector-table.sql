create extension if not exists vector with schema extensions;

create table public.vector_table (
    vector_id bigint generated by default as identity primary key,
    embedding vector(1024) not null -- Qwen3-Embedding-0.6B outputs 1024-dimensional vectors
);

--  use HNSW algorithm to create an index for auto-linking to similar neighbors for efficient similarity search.
create index on public.vector_table using hnsw (embedding vector_cosine_ops);
